        private static bool HandleBindingMatches(INamedTypeSymbol handle, AttributeData binding, string fieldId)
        {
            var args = binding.ConstructorArguments; var bindingName = binding.AttributeClass?.ToDisplayString();
            if (args.Length == 0 || args[0].Value as string != fieldId) return false;
            var generic = handle.ConstructedFrom.ToDisplayString();
            if (generic == "AIBT.Burst.BlackboardReadHandle<T>" || generic == "AIBT.Burst.BlackboardWriteHandle<T>" || generic == "AIBT.Burst.BlackboardReadWriteHandle<T>")
            {
                if (bindingName != "AIBT.Burst.AibtBlackboardBindingAttribute" || args.Length != 5) return false;
                var expectedAccess = generic == "AIBT.Burst.BlackboardReadHandle<T>" ? 0 : generic == "AIBT.Burst.BlackboardWriteHandle<T>" ? 1 : 2;
                var access = Convert.ToInt32(args[1].Value, CultureInfo.InvariantCulture); var scope = Convert.ToInt32(args[2].Value, CultureInfo.InvariantCulture);
                return access == expectedAccess && !(scope == 3 && access != 0) && args[3].Value is string id && args[4].Value is uint version
                    && PrimitiveIdentityMatches(handle.TypeArguments[0], id, version);
            }
            if (generic == "AIBT.Burst.AsyncOperationHandle<TStart, TCancel>")
                return bindingName == "AIBT.Burst.AibtAsyncOperationBindingAttribute" && args.Length == 5
                    && args[1].Value is string startId && args[2].Value is uint startVersion && PrimitiveIdentityMatches(handle.TypeArguments[0], startId, startVersion)
                    && args[3].Value is string cancelId && args[4].Value is uint cancelVersion && PrimitiveIdentityMatches(handle.TypeArguments[1], cancelId, cancelVersion);
            var expectedName = generic == "AIBT.Burst.SnapshotReadHandle<T>" ? "AIBT.Burst.AibtSnapshotBindingAttribute"
                : generic == "AIBT.Burst.CommandHandle<T>" ? "AIBT.Burst.AibtCommandBindingAttribute" : "AIBT.Burst.AibtCompletionBindingAttribute";
            return bindingName == expectedName && args.Length == 3 && args[1].Value is string typeId && args[2].Value is uint typeVersion
                && PrimitiveIdentityMatches(handle.TypeArguments[0], typeId, typeVersion);
        }

        private static bool Callback(SourceProductionContext context, Node node, string name, string returnType, string contextType, string? reasonType)
        {
            var methods = node.Type.GetMembers(name).OfType<IMethodSymbol>().ToArray();
            var ok = methods.Length == 1 && CommonCallback(methods[0], node, returnType, contextType, reasonType);
            if (!ok) ReportAt(context, AbiDiagnostics.Callback, CallbackLocation(methods, node.Type), node.Type.Name, name);
            return ok;
        }

        private static bool CommonCallback(IMethodSymbol method, Node node, string returnType, string contextType, string? reasonType)
        {
            if (!method.IsStatic || method.DeclaredAccessibility != Accessibility.Public || method.IsGenericMethod
                || (returnType == "System.Void" ? !method.ReturnsVoid : method.ReturnType.ToDisplayString() != returnType)) return false;
            var expected = reasonType == null ? 3 : 4;
            if (method.Parameters.Length != expected) return false;
            return SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, node.Config) && method.Parameters[0].RefKind == RefKind.In
                && SymbolEqualityComparer.Default.Equals(method.Parameters[1].Type, node.Memory) && method.Parameters[1].RefKind == RefKind.Ref
                && method.Parameters[2].Type.ToDisplayString() == contextType && method.Parameters[2].RefKind == RefKind.Ref
                && (reasonType == null || (method.Parameters[3].Type.ToDisplayString() == reasonType && method.Parameters[3].RefKind == RefKind.None));
        }

        private static bool ObserverCallback(SourceProductionContext context, Node node, IMethodSymbol[] methods)
        {
            var ok = methods.Length == 1;
            if (ok)
            {
                var method = methods[0];
                ok = method.IsStatic && method.DeclaredAccessibility == Accessibility.Public && !method.IsGenericMethod
                    && method.ReturnType.ToDisplayString() == "AIBT.Burst.ConditionResult" && method.Parameters.Length == 2
                    && SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, node.Config) && method.Parameters[0].RefKind == RefKind.In
                    && method.Parameters[1].Type.ToDisplayString() == "AIBT.Burst.BurstObserverContext" && method.Parameters[1].RefKind == RefKind.Ref;
            }
            if (!ok) ReportAt(context, AbiDiagnostics.Callback, CallbackLocation(methods, node.Type), node.Type.Name, "Evaluate");
            return ok;
        }

        private static bool ValidateShard(SourceProductionContext context, INamedTypeSymbol shard)
        {
            var partial = shard.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<StructDeclarationSyntax>()
                .Any(declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
            var valid = shard.TypeKind == TypeKind.Struct && shard.DeclaredAccessibility == Accessibility.Public && shard.ContainingType == null
                && shard.Arity == 0 && !shard.GetMembers().OfType<IFieldSymbol>().Any(field => !field.IsImplicitlyDeclared) && !shard.GetMembers("BurstAccess").Any()
                && !shard.GetMembers("IsUsable").Any() && !shard.GetMembers("AbiVersion").Any() && partial;
            var attribute = Attribute(shard, ShardAttribute);
            if (attribute == null || attribute.ConstructorArguments.Length != 2 || !(attribute.ConstructorArguments[0].Value is string id)
                || !Canonical(id) || !(attribute.ConstructorArguments[1].Value is uint version) || version == 0)
            {
                ReportAt(context, AbiDiagnostics.Identity, attribute == null ? shard.Locations.FirstOrDefault() : AttributeLocation(attribute, attribute.ConstructorArguments.Length > 1 && attribute.ConstructorArguments[1].Value is uint zero && zero == 0 ? 1 : 0), shard.Name);
                valid = false;
            }
            if (!valid)
                Report(context, AbiDiagnostics.Catalog, shard, shard.Name, "shard must be a public top-level non-generic fieldless partial struct");
            return valid;
        }

        private static void EmitCatalog(SourceProductionContext context, INamedTypeSymbol catalogSet)
        {
            var attribute = Attribute(catalogSet, CatalogSetAttribute);
            var invalidReason = ValidateCatalogSetShape(catalogSet);
            Location? catalogFailureLocation = null;
            var shardTypes = new List<INamedTypeSymbol>();
            if (attribute == null || attribute.ConstructorArguments.Length != 3) invalidReason = "catalog attribute arguments are invalid";
            else
            {
                if (!(attribute.ConstructorArguments[0].Value is string catalogId) || !Canonical(catalogId)
                    || !(attribute.ConstructorArguments[1].Value is uint catalogVersion) || catalogVersion == 0)
                {
                    ReportAt(context, AbiDiagnostics.Identity, AttributeLocation(attribute, attribute.ConstructorArguments[1].Value is uint zero && zero == 0 ? 1 : 0), catalogSet.Name);
                    invalidReason = "catalog identity or version is invalid";
                }
                var selected = attribute.ConstructorArguments[2].Values;
                for (var selectedIndex = 0; selectedIndex < selected.Length; selectedIndex++)
                    if (selected[selectedIndex].Value is INamedTypeSymbol shard) shardTypes.Add(shard); else { invalidReason = "catalog shard type is invalid"; catalogFailureLocation = AttributeLocation(attribute, 2 + selectedIndex); }
            }
            if (shardTypes.Count == 0) invalidReason = "catalog must select at least one shard";
            if (shardTypes.Distinct(SymbolEqualityComparer.Default).Count() != shardTypes.Count) invalidReason = "catalog shard types must be unique";
            var abiMismatch = false;
            for (var shardIndex = 0; shardIndex < shardTypes.Count; shardIndex++)
            {
                var shard = shardTypes[shardIndex];
                var usable = shard.GetMembers("IsUsable").OfType<IFieldSymbol>().Where(field => field.IsConst && field.Type.SpecialType == SpecialType.System_Boolean).ToArray();
                var abi = shard.GetMembers("AbiVersion").OfType<IFieldSymbol>().Where(field => field.IsConst && field.Type.SpecialType == SpecialType.System_UInt32).ToArray();
                if (Attribute(shard, ShardAttribute) == null || usable.Length != 1 || !(usable[0].ConstantValue is bool isUsable) || !isUsable || abi.Length != 1)
                { invalidReason = "selected type '" + shard.Name + "' lacks a usable generated shard authority"; catalogFailureLocation = AttributeLocation(attribute!, 2 + shardIndex); }
                else if (!(abi[0].ConstantValue is uint version) || version != 1u) { invalidReason = "selected shard ABI version mismatch"; catalogFailureLocation = AttributeLocation(attribute!, 2 + shardIndex); abiMismatch = true; }
            }

            var nodes = shardTypes.SelectMany(shard => AllTypes(shard.ContainingAssembly.GlobalNamespace))
                .Where(type => Attribute(type, NodeAttribute) != null).Select(ReadNode).OrderBy(NodeOrder).ToArray();
            var validNodes = ValidateNodes(context, nodes, true, false);
            if (validNodes.Count != nodes.Length)
            {
                invalidReason = "one or more selected shards contain a global node identity conflict";
                var validTypes = new HashSet<INamedTypeSymbol>(validNodes.Select(node => node.Type), SymbolEqualityComparer.Default);
                var invalidAssemblies = new HashSet<IAssemblySymbol>(nodes.Where(node => !validTypes.Contains(node.Type)).Select(node => node.Type.ContainingAssembly), SymbolEqualityComparer.Default);
                for (var shardIndex = shardTypes.Count - 1; shardIndex >= 0; shardIndex--)
                    if (invalidAssemblies.Contains(shardTypes[shardIndex].ContainingAssembly)) { catalogFailureLocation = AttributeLocation(attribute!, 2 + shardIndex); break; }
            }

            if (invalidReason != null)
            {
                if (abiMismatch) ReportAt(context, AbiDiagnostics.Handshake, Location.None, invalidReason);
                else if (catalogFailureLocation != null) ReportAt(context, AbiDiagnostics.Catalog, catalogFailureLocation, catalogSet.Name, invalidReason);
                else Report(context, AbiDiagnostics.Catalog, catalogSet, catalogSet.Name, invalidReason);
                context.AddSource(Safe(catalogSet) + ".CatalogSet.g.cs", SourceText.From(EmitUnusable(catalogSet), Encoding.UTF8));
                return;
            }
            context.AddSource(Safe(catalogSet) + ".CatalogSet.g.cs", SourceText.From(EmitFacade(catalogSet, shardTypes, validNodes), Encoding.UTF8));
        }

        private static string? ValidateCatalogSetShape(INamedTypeSymbol type)
        {
            var partial = type.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<ClassDeclarationSyntax>()
                .Any(declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword) && declaration.Modifiers.Any(SyntaxKind.StaticKeyword));
            return type.TypeKind == TypeKind.Class && type.IsStatic && type.DeclaredAccessibility == Accessibility.Public
                && type.ContainingType == null && type.Arity == 0 && partial ? null : "catalog set must be a public top-level non-generic static partial class";
        }

