        private static byte[] StorageHash(Node node, INamedTypeSymbol storage, bool configuration)
        {
            var physical = storage.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared)
                .OrderBy(StableFieldId, Utf8StringComparer.Instance).Select(FieldLayout.Create).ToArray();
            uint offset = 0; byte aggregateAlignment = 1;
            foreach (var field in physical)
            {
                offset = Align(offset, field.Alignment); field.Offset = offset; offset += field.Size;
                if (field.Alignment > aggregateAlignment) aggregateAlignment = field.Alignment;
            }
            var totalSize = Align(offset, aggregateAlignment);
            var bytes = new CanonicalBytes(); bytes.Raw(configuration ? "AIBT-CONFIG-LAYOUT-V1\0" : "AIBT-MEMORY-LAYOUT-V1\0");
            bytes.U32(1); bytes.S(node.TypeId); bytes.U32(node.Version); bytes.U32(totalSize); bytes.U8(aggregateAlignment); bytes.U32((uint)physical.Length);
            foreach (var field in physical.OrderBy(field => field.Id, Utf8StringComparer.Instance))
            {
                bytes.S(field.Id); bytes.U64(NumericId(field.Id)); bytes.S(field.ValueTypeId); bytes.U32(field.ValueVersion);
                bytes.H32(field.SchemaHash); bytes.U32(field.Offset); bytes.U32(field.Size); bytes.U8(field.Alignment); bytes.U8(field.Encoding);
            }
            var padding = new List<PaddingRange>(); uint cursor = 0;
            foreach (var field in physical.OrderBy(field => field.Offset))
            { if (field.Offset > cursor) padding.Add(new PaddingRange(cursor, field.Offset - cursor)); cursor = field.Offset + field.Size; }
            if (totalSize > cursor) padding.Add(new PaddingRange(cursor, totalSize - cursor));
            bytes.U32((uint)padding.Count); foreach (var range in padding) { bytes.U32(range.Offset); bytes.U32(range.Size); }
            return bytes.Hash();
        }

        private static byte[] AccessHash(Node node)
        {
            var bindings = node.Config!.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared)
                .Select(BindingRecord.TryCreate).Where(binding => binding != null).Cast<BindingRecord>()
