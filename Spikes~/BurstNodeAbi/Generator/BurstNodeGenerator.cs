            for (uint ordinal = 0; ordinal < bindings.Length; ordinal++)
            {
                var binding = bindings[ordinal]; bytes.S(binding.Id); bytes.U64(NumericId(binding.Id)); bytes.U8(binding.Kind);
                bytes.U8(binding.Scope); bytes.U8(binding.PhaseMask); bytes.U32(ordinal); bytes.U32((uint)binding.Types.Length);
                foreach (var type in binding.Types.OrderBy(type => type.Role))
                { bytes.U8(type.Role); bytes.S(type.Id); bytes.U64(NumericId(type.Id)); bytes.U32(type.Version); bytes.H32(RegisteredSchemaHash(type.Type)); }
            }
            return bytes.Hash();
        }

        private static uint Align(uint value, byte alignment) => (value + alignment - 1u) & ~(uint)(alignment - 1u);
        private static byte[] RegisteredSchemaHash(ITypeSymbol? type)
        {
            if (!(type is INamedTypeSymbol named)) return new byte[32];
            var attribute = Attribute(named, ValueAttribute); if (attribute == null) return new byte[32];
            var layout = DescribeLayout(named); var bytes = new CanonicalBytes(); bytes.Raw("AIBT-VALUE-SCHEMA-V1\0"); bytes.U32(1);
            var typeId = (string)attribute.ConstructorArguments[0].Value!; var version = (uint)attribute.ConstructorArguments[1].Value!; var schemaId = (string)attribute.ConstructorArguments[2].Value!;
            bytes.S(typeId); bytes.U64(NumericId(typeId)); bytes.U32(version); bytes.S(schemaId); bytes.U64(NumericId(schemaId));
            bytes.U32(layout.Size); bytes.U8(layout.Alignment); bytes.U32((uint)layout.Fields.Length);
            foreach (var field in layout.Fields)
            {
                bytes.S(field.Id); bytes.U64(NumericId(field.Id)); bytes.S(field.ValueTypeId); bytes.U64(NumericId(field.ValueTypeId)); bytes.U32(field.ValueVersion);
                bytes.H32(RegisteredSchemaHash(field.Field.Type)); bytes.U32(field.Offset); bytes.U32(field.Size); bytes.U8(field.Alignment); bytes.U8(field.Encoding);
            }
            return bytes.Hash();
        }
        private static string HashLiteral(byte[] hash)
        {
            var words = new string[8];
            for (var index = 0; index < words.Length; index++)
            {
                var offset = index * 4; var value = (uint)(hash[offset] | hash[offset + 1] << 8 | hash[offset + 2] << 16 | hash[offset + 3] << 24);
                words[index] = "0x" + value.ToString("x8", CultureInfo.InvariantCulture) + "u";
            }
            return "new global::AIBT.Burst.BurstHash256(" + string.Join(", ", words) + ")";
        }

        private sealed class CanonicalBytes
        {
            private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false, true);
            private readonly List<byte> bytes = new List<byte>();
            internal void Raw(string value) => bytes.AddRange(Utf8.GetBytes(value));
            internal void U8(byte value) => bytes.Add(value);
            internal void U32(uint value) { bytes.Add((byte)value); bytes.Add((byte)(value >> 8)); bytes.Add((byte)(value >> 16)); bytes.Add((byte)(value >> 24)); }
            internal void U64(ulong value) { U32((uint)value); U32((uint)(value >> 32)); }
            internal void S(string value) { var encoded = Utf8.GetBytes(value); U32((uint)encoded.Length); bytes.AddRange(encoded); }
            internal void H32(byte[] value) { if (value.Length != 32) throw new InvalidDataException("H32 requires exactly 32 bytes."); bytes.AddRange(value); }
            internal byte[] Hash() { using (var sha = SHA256.Create()) return sha.ComputeHash(bytes.ToArray()); }
        }

        private sealed class Utf8StringComparer : IComparer<string>
        {
            internal static readonly Utf8StringComparer Instance = new Utf8StringComparer();
            private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false, true);
            public int Compare(string left, string right)
            {
                if (ReferenceEquals(left, right)) return 0; if (left == null) return -1; if (right == null) return 1;
                var leftBytes = Utf8.GetBytes(left); var rightBytes = Utf8.GetBytes(right); var count = Math.Min(leftBytes.Length, rightBytes.Length);
                for (var index = 0; index < count; index++) if (leftBytes[index] != rightBytes[index]) return leftBytes[index] < rightBytes[index] ? -1 : 1;
                return leftBytes.Length.CompareTo(rightBytes.Length);
            }
        }

