        private static void ReportFieldCollision(SourceProductionContext context, StableField first, StableField second)
        {
            StableField primary; StableField additional;
            var order = Utf8StringComparer.Instance.Compare(first.Id, second.Id);
            if (order < 0) { primary = second; additional = first; }
            else if (order > 0) { primary = first; additional = second; }
            else if (string.CompareOrdinal(SourceOrder(first.Field), SourceOrder(second.Field)) <= 0) { primary = second; additional = first; }
            else { primary = first; additional = second; }
            ReportLocationCollision(context, AbiDiagnostics.NumericCollision, AttributeLocation(primary.Attribute, 0), AttributeLocation(additional.Attribute, 0), additional.Id, primary.Id);
        }
