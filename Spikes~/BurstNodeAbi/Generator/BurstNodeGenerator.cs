        private static LayoutDescription DescribeLayout(INamedTypeSymbol storage)
        {
            var fields = storage.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared)
                .OrderBy(StableFieldId, Utf8StringComparer.Instance).Select(FieldLayout.Create).ToArray();
            uint offset = 0; byte alignment = 1;
            foreach (var field in fields) { offset = Align(offset, field.Alignment); field.Offset = offset; offset += field.Size; if (field.Alignment > alignment) alignment = field.Alignment; }
            return new LayoutDescription(fields, Align(offset, alignment), alignment);
        }

