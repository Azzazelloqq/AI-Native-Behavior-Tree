        private const string NodeAttribute = "AIBT.Burst.AibtBurstNodeAttribute";
        private const string DocumentationAttribute = "AIBT.Burst.AibtNodeDocumentationAttribute";
        private const string ObserverAttribute = "AIBT.Burst.AibtObserverConditionAttribute";
        private const string RandomAttribute = "AIBT.Burst.AibtRandomStreamAttribute";
        private const string ShardAttribute = "AIBT.Burst.AibtCatalogShardAttribute";
        private const string CatalogSetAttribute = "AIBT.Burst.AibtCatalogSetAttribute";
        private const string ConfigFieldAttribute = "AIBT.Burst.AibtConfigFieldAttribute";
        private const string MemoryFieldAttribute = "AIBT.Burst.AibtMemoryFieldAttribute";
        private const string ValueAttribute = "AIBT.Burst.AibtBurstValueAttribute";
        private const string ValueFieldAttribute = "AIBT.Burst.AibtValueFieldAttribute";

        // Isolated runner seam for proving AIBT5010 without relying on a practical 64-bit collision search.
        public static bool ForceNumericIdentityCollisionForTests { get; set; }
        public static ulong NumericIdentityForTests(string canonicalId) => NumericId(canonicalId);

        public void Initialize(IncrementalGeneratorInitializationContext context)
            => context.RegisterSourceOutput(context.CompilationProvider, static (production, compilation) => Execute(production, compilation));

        private static void Execute(SourceProductionContext context, Compilation compilation)
        {
            var localTypes = AllTypes(compilation.Assembly.GlobalNamespace).ToArray();
            var localNodes = localTypes.Where(type => Attribute(type, NodeAttribute) != null).Select(ReadNode).OrderBy(NodeOrder).ToArray();
            var validLocalNodes = ValidateNodes(context, localNodes, true, true);
            var valuesValid = ValidateRegisteredValues(context, localTypes.Where(type => Attribute(type, ValueAttribute) != null).ToArray());
            var unresolvedUsageValid = ValidateUnresolvedUsage(context, compilation);

            var shards = localTypes.Where(type => Attribute(type, ShardAttribute) != null).ToArray();
            var shardSetValid = localNodes.Length == validLocalNodes.Count && valuesValid && unresolvedUsageValid && shards.Length == 1
                && !BurstNodeUsageAnalyzer.HasInvalidUsage(compilation);
            if (localNodes.Length > 0 && shards.Length != 1)
            {
                foreach (var node in localNodes)
                    Report(context, AbiDiagnostics.Catalog, node.Type, node.Type.Name, "a node assembly must declare exactly one shard");
                if (shards.Length == 0) context.AddSource("AibtUnusableShard.g.cs", SourceText.From("// <auto-generated/>\ninternal static class __AibtUnusableShardMarker { internal const bool IsUsable = false; }\n", Encoding.UTF8));
            }
            foreach (var shard in shards)
            {
                var valid = shardSetValid && ValidateShard(context, shard);
                context.AddSource(Safe(shard) + ".BurstCatalogShard.g.cs", SourceText.From(valid ? EmitShard(shard, validLocalNodes, localTypes) : EmitUnusableShard(shard), Encoding.UTF8));
            }

            foreach (var catalogSet in localTypes.Where(type => Attribute(type, CatalogSetAttribute) != null).OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal))
                EmitCatalog(context, catalogSet);
        }

        private static bool ValidateUnresolvedUsage(SourceProductionContext context, Compilation compilation)
        {
            var valid = true;
            foreach (var tree in compilation.SyntaxTrees)
            {
                var model = compilation.GetSemanticModel(tree);
                foreach (var invocation in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
                {
                    if (model.GetSymbolInfo(invocation).Symbol != null || !invocation.Expression.ToString().Contains(".BurstAccess.", StringComparison.Ordinal)) continue;
                    var declaration = invocation.FirstAncestorOrSelf<MethodDeclarationSyntax>();
                    var callback = declaration == null ? null : model.GetDeclaredSymbol(declaration) as IMethodSymbol;
                    if (callback == null || Attribute(callback.ContainingType, NodeAttribute) == null) continue;
                    var operation = (invocation.Expression as MemberAccessExpressionSyntax)?.Name.Identifier.ValueText ?? string.Empty;
                    var expected = ExpectedBindingAttributes(operation);
                    if (expected == null || BurstNodeUsageAnalyzer.ValidUnresolvedBinding(model, invocation, callback, operation, expected, 1)) continue;
                    valid = false;
                    var argument = invocation.ArgumentList.Arguments.Count > 1 ? invocation.ArgumentList.Arguments[1].Expression : invocation;
                    var field = model.GetSymbolInfo(argument).Symbol as IFieldSymbol;
                    if (field?.Type is INamedTypeSymbol handle && handle.IsGenericType)
                    {
                        var fieldBindings = field.GetAttributes().Where(IsBindingAttribute).ToArray();
                        if (fieldBindings.Length == 1 && !HandleBindingMatches(handle, fieldBindings[0], StableFieldId(field))) continue;
                    }
                    context.ReportDiagnostic(field == null
                        ? Diagnostic.Create(AbiDiagnostics.UndeclaredAccess, invocation.GetLocation(), operation)
                        : Diagnostic.Create(AbiDiagnostics.WrongAccess, invocation.GetLocation(), operation, field.Name));
                }
            }
            return valid;
        }

        private static string[]? ExpectedBindingAttributes(string operation)
        {
            switch (operation)
            {
                case "TryRead": case "TryWrite": return new[] { "AIBT.Burst.AibtBlackboardBindingAttribute" };
                case "TryReadSnapshot": return new[] { "AIBT.Burst.AibtSnapshotBindingAttribute" };
                case "TryEmit": return new[] { "AIBT.Burst.AibtCommandBindingAttribute" };
                case "TryStart": case "TryCancel": return new[] { "AIBT.Burst.AibtAsyncOperationBindingAttribute" };
                case "TryConsume": return new[] { "AIBT.Burst.AibtCompletionBindingAttribute" };
                default: return null;
            }
        }

        private static List<Node> ValidateNodes(SourceProductionContext context, IEnumerable<Node> nodes, bool reportGlobal, bool validateLocalDeclarations, bool reportCollisionDiagnostics = true)
        {
            var ordered = nodes.OrderBy(NodeOrder).ToArray();
            var invalid = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
            foreach (var group in ordered.GroupBy(node => node.TypeId + "\u001f" + node.Version.ToString(CultureInfo.InvariantCulture), StringComparer.Ordinal))
            {
                if (group.Count() <= 1) continue;
                var collisions = group.OrderBy(node => DiagnosticOrder(node.Type), StringComparer.Ordinal).ToArray();
                if (reportCollisionDiagnostics)
                    ReportNodeCollision(context, AbiDiagnostics.Duplicate, collisions[collisions.Length - 1],
                        collisions.Take(collisions.Length - 1), collisions[0].TypeId, collisions[0].Version);
                foreach (var node in collisions) invalid.Add(node.Type);
            }

            if (reportGlobal)
            {
                foreach (var group in ordered.GroupBy(node => NumericId(node.TypeId)))
                {
                    var identities = group.Select(node => node.TypeId).Distinct(StringComparer.Ordinal).ToArray();
                    if (identities.Length <= 1) continue;
                    var identityOrder = identities.OrderBy(value => value, Utf8StringComparer.Instance).ToArray();
                    var primary = group.Where(node => node.TypeId == identityOrder[identityOrder.Length - 1]).OrderBy(node => DiagnosticOrder(node.Type), StringComparer.Ordinal).Last();
                    if (reportCollisionDiagnostics)
                        ReportNodeCollision(context, AbiDiagnostics.NumericCollision, primary, group.Where(node => !SymbolEqualityComparer.Default.Equals(node.Type, primary.Type)), identityOrder[0], identityOrder[identityOrder.Length - 1]);
                    foreach (var node in group) invalid.Add(node.Type);
                }
            }

            if (validateLocalDeclarations)
                foreach (var node in ordered)
                    if (!ValidateNode(context, node)) invalid.Add(node.Type);
            return ordered.Where(node => !invalid.Contains(node.Type)).ToList();
        }

        private static bool ValidateNode(SourceProductionContext context, Node node)
        {
            var valid = true;
            if (node.Type.TypeKind != TypeKind.Struct || node.Type.DeclaredAccessibility != Accessibility.Public
                || node.Type.ContainingType != null || node.Type.Arity != 0 || node.Type.IsGenericType
                || node.Type.GetMembers().OfType<IFieldSymbol>().Any(field => !field.IsImplicitlyDeclared)
                || !node.Type.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<StructDeclarationSyntax>()
                    .Any(declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword)))
            {
                var offendingField = node.Type.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(field => !field.IsImplicitlyDeclared);
                if (offendingField != null) Report(context, AbiDiagnostics.DeclarationShape, offendingField, node.Type.Name);
                else Report(context, AbiDiagnostics.DeclarationShape, node.Type, node.Type.Name);
                valid = false;
            }

            var nodeAttribute = Attribute(node.Type, NodeAttribute)!;
            var documentation = Attribute(node.Type, DocumentationAttribute);
            if (!Canonical(node.TypeId) || node.Version == 0 || !ValidDocumentation(node.Type))
            {
                var location = !Canonical(node.TypeId) ? AttributeLocation(nodeAttribute, 0) : node.Version == 0 ? AttributeLocation(nodeAttribute, 1) : DocumentationLocation(documentation);
                ReportAt(context, AbiDiagnostics.Identity, location, node.Type.Name);
                valid = false;
            }

            var observerAttribute = Attribute(node.Type, ObserverAttribute); var observer = observerAttribute != null;
            if ((node.Kind != 0 && node.Kind != 1) || (observer && node.Kind != 0))
            {
                ReportAt(context, AbiDiagnostics.Kind, observer && (node.Kind == 0 || node.Kind == 1) ? AttributeLocation(observerAttribute!, -1) : AttributeLocation(nodeAttribute, 2), node.Type.Name);
                valid = false;
            }
            var cancellation = Convert.ToByte(nodeAttribute.ConstructorArguments[7].Value, CultureInfo.InvariantCulture);
            var statuses = Convert.ToByte(nodeAttribute.ConstructorArguments[9].Value, CultureInfo.InvariantCulture);
            var asyncBindings = node.Config?.GetMembers().OfType<IFieldSymbol>()
                .SelectMany(field => field.GetAttributes()
                    .Where(value => value.AttributeClass?.ToDisplayString() == "AIBT.Burst.AibtAsyncOperationBindingAttribute")
                    .Select(attribute => (Field: field, Attribute: attribute)))
                .OrderBy(value => SourceOrder(value.Field), StringComparer.Ordinal).ToArray()
                ?? Array.Empty<(IFieldSymbol Field, AttributeData Attribute)>();
            if ((cancellation == 0 && (statuses & 4) != 0)
                || (cancellation == 2 && ((statuses & 4) == 0 || asyncBindings.Length == 0)) || cancellation > 2)
            {
                var argument = cancellation == 2 && (statuses & 4) == 0 ? 9 : 7;
                ReportAt(context, AbiDiagnostics.Kind, AttributeLocation(nodeAttribute, argument), node.Type.Name);
                valid = false;
            }
            if (cancellation == 0 || cancellation == 1)
            {
                foreach (var asyncBinding in asyncBindings)
                    ReportAt(context, AbiDiagnostics.WrongAccess, AttributeLocation(asyncBinding.Attribute, -1), asyncBinding.Field.Name, "async-operation-binding");
                if (asyncBindings.Length != 0) valid = false;
            }

            valid &= ValidateStorage(context, node, node.Config, ConfigFieldAttribute, "configuration");
            valid &= ValidateStorage(context, node, node.Memory, MemoryFieldAttribute, "memory");
            valid &= Callback(context, node, "Enter", "System.Void", "AIBT.Burst.BurstEnterContext", null);
            valid &= Callback(context, node, "Tick", "AIBT.NodeStatus", "AIBT.Burst.BurstTickContext", null);
            valid &= Callback(context, node, "Abort", "System.Void", "AIBT.Burst.BurstAbortContext", "AIBT.Burst.BurstNodeAbortReason");
            valid &= Callback(context, node, "Exit", "System.Void", "AIBT.Burst.BurstExitContext", "AIBT.Burst.BurstNodeExitReason");

            var evaluate = node.Type.GetMembers("Evaluate").OfType<IMethodSymbol>().ToArray();
            if (observer)
                valid &= ObserverCallback(context, node, evaluate);
            else if (evaluate.Length != 0)
            {
                ReportAt(context, AbiDiagnostics.Kind, AttributeLocation(nodeAttribute, 2), node.Type.Name);
                valid = false;
            }
            return valid;
        }

        private static bool ValidateStorage(SourceProductionContext context, Node node, INamedTypeSymbol? type, string fieldAttribute, string label)
        {
            string? reason = null;
            if (type == null || type.TypeKind != TypeKind.Struct || type.Arity != 0 || !type.IsUnmanagedType
                || type.DeclaredAccessibility != Accessibility.Public || type.ContainingType != null
                || !type.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<StructDeclarationSyntax>()
                    .Any(declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword)))
                reason = label + " must be a public top-level non-generic unmanaged partial struct";
            else
            {
                var explicitLayout = type.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Runtime.InteropServices.StructLayoutAttribute");
                if (explicitLayout != null)
                {
                    ReportAt(context, AbiDiagnostics.Storage, AttributeLocation(explicitLayout, -1), node.Type.Name, label + " uses forbidden explicit StructLayout");
                    return false;
                }
                var mutableStatic = type.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(field => field.IsStatic && !field.IsConst && !field.IsImplicitlyDeclared);
                if (mutableStatic != null)
                {
                    Report(context, AbiDiagnostics.Storage, mutableStatic, node.Type.Name, label + " contains static mutable storage");
                    return false;
                }
                var autoProperty = type.GetMembers().OfType<IPropertySymbol>().FirstOrDefault(property => !property.IsStatic && property.DeclaringSyntaxReferences
                    .Select(reference => reference.GetSyntax()).OfType<PropertyDeclarationSyntax>()
                    .Any(syntax => syntax.AccessorList != null && syntax.AccessorList.Accessors.Any(accessor => accessor.Body == null && accessor.ExpressionBody == null)));
                if (autoProperty != null)
                {
                    Report(context, AbiDiagnostics.Storage, autoProperty, node.Type.Name, label + " contains auto-property storage");
                    return false;
                }
                if (type.GetTypeMembers("BurstCodec").Length != 0)
                {
                    Report(context, AbiDiagnostics.Storage, type.GetTypeMembers("BurstCodec")[0], node.Type.Name, label + " reserves generated member BurstCodec");
                    return false;
                }
                var fields = type.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared).ToArray();
                foreach (var field in fields)
                {
                    if (!AllowedType(field.Type, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), out var fieldReason))
                    { Report(context, AbiDiagnostics.Storage, field, node.Type.Name, label + ": " + fieldReason); return false; }
                    if (fieldAttribute == ConfigFieldAttribute && !AllowedConfigurationField(field.Type))
                    { Report(context, AbiDiagnostics.Storage, field, node.Type.Name, "configuration field type is outside the closed bool/uint/ulong/handle allowlist"); return false; }
                    var attributes = field.GetAttributes(); var stableAttributes = attributes.Where(attribute => attribute.AttributeClass?.ToDisplayString() == fieldAttribute).ToArray();
                    if (field.DeclaredAccessibility != Accessibility.Public || stableAttributes.Length != 1)
                    {
                        Report(context, AbiDiagnostics.Storage, field, node.Type.Name, label + " field '" + field.Name + "' requires exactly one stable field attribute and public accessibility");
                        return false;
                    }
                    var stable = stableAttributes[0];
                    if (stable.ConstructorArguments.Length != 3 || !(stable.ConstructorArguments[0].Value is string fieldId) || !CanonicalField(fieldId)
                        || !(stable.ConstructorArguments[1].Value is string valueTypeId) || !(stable.ConstructorArguments[2].Value is uint version) || version == 0)
                    { var location = !(stable.ConstructorArguments[0].Value is string candidateId) || !CanonicalField(candidateId) ? AttributeLocation(stable, 0) : AttributeLocation(stable, 2); ReportAt(context, AbiDiagnostics.Identity, location, field.Name); return false; }
                    if (!PrimitiveIdentityMatches(field.Type, valueTypeId, version))
                    { ReportAt(context, AbiDiagnostics.WrongAccess, IdentityMismatchLocation(stable, field.Type), field.Name, valueTypeId); return false; }
                    var namedField = field.Type as INamedTypeSymbol;
                    var isHandle = namedField != null && namedField.IsGenericType && IsGeneratedHandle(namedField.ConstructedFrom.ToDisplayString());
                    var bindings = attributes.Where(IsBindingAttribute).ToArray();
                    if ((isHandle && (bindings.Length != 1 || !HandleBindingMatches(namedField!, bindings[0], fieldId))) || (!isHandle && bindings.Length != 0))
                    { ReportAt(context, AbiDiagnostics.WrongAccess, bindings.Length == 0 ? field.Locations.FirstOrDefault() : BindingMismatchLocation(namedField!, bindings[0], fieldId), field.Name, bindings.Length == 0 ? "missing-binding" : bindings[0].AttributeClass?.Name ?? "binding"); return false; }
                    if (field.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Runtime.InteropServices.FieldOffsetAttribute"))
                    { Report(context, AbiDiagnostics.Storage, field, node.Type.Name, label + " field uses forbidden FieldOffset"); return false; }
                }
                var ordered = fields.Select(field => new StableField(field, field.GetAttributes().Single(attribute => attribute.AttributeClass?.ToDisplayString() == fieldAttribute)))
                    .OrderBy(field => SourceOrder(field.Field), StringComparer.Ordinal).ToArray();
                for (var later = 0; later < ordered.Length; later++)
                    for (var earlier = 0; earlier < later; earlier++)
                        if (ordered[later].Id == ordered[earlier].Id || NumericId(ordered[later].Id) == NumericId(ordered[earlier].Id))
                        {
                            ReportFieldCollision(context, ordered[earlier], ordered[later]);
                            return false;
                        }
            }
            if (reason == null) return true;
            if (type != null) Report(context, AbiDiagnostics.Storage, type, node.Type.Name, reason); else Report(context, AbiDiagnostics.Storage, node.Type, node.Type.Name, reason);
            return false;
        }

        private static bool ValidateRegisteredValues(SourceProductionContext context, IReadOnlyList<INamedTypeSymbol> values)
        {
            var valid = true;
            foreach (var type in values)
            {
                var partial = type.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<StructDeclarationSyntax>()
                    .Any(declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
                var attribute = Attribute(type, ValueAttribute)!;
                if (type.TypeKind != TypeKind.Struct || type.DeclaredAccessibility != Accessibility.Public || type.ContainingType != null || type.Arity != 0 || !type.IsUnmanagedType || !partial)
                { Report(context, AbiDiagnostics.Storage, type, type.Name, "registered value must be a public top-level non-generic unmanaged partial struct"); valid = false; continue; }
                if (attribute.ConstructorArguments.Length != 3 || !(attribute.ConstructorArguments[0].Value is string typeId) || !Canonical(typeId)
                    || !(attribute.ConstructorArguments[1].Value is uint version) || version == 0 || !(attribute.ConstructorArguments[2].Value is string schemaId) || !Canonical(schemaId))
                { var location = !(attribute.ConstructorArguments[0].Value is string candidateType) || !Canonical(candidateType) ? AttributeLocation(attribute, 0) : !(attribute.ConstructorArguments[1].Value is uint candidateVersion) || candidateVersion == 0 ? AttributeLocation(attribute, 1) : AttributeLocation(attribute, 2); ReportAt(context, AbiDiagnostics.Identity, location, type.Name); valid = false; continue; }
                var hasAutoProperty = type.GetMembers().OfType<IPropertySymbol>().Any(property => !property.IsStatic && property.DeclaringSyntaxReferences
                    .Select(reference => reference.GetSyntax()).OfType<PropertyDeclarationSyntax>()
                    .Any(syntax => syntax.AccessorList != null && syntax.AccessorList.Accessors.Any(accessor => accessor.Body == null && accessor.ExpressionBody == null)));
                var hasEqualityContract = type.AllInterfaces.Any(value => value.OriginalDefinition.ToDisplayString() == "System.IEquatable<T>")
                    || type.GetMembers().OfType<IMethodSymbol>().Any(method => !method.IsImplicitlyDeclared
                        && (method.Name == "Equals" || method.Name == "GetHashCode" || method.Name == "op_Equality" || method.Name == "op_Inequality"
                            || method.Name.IndexOf("Serialize", StringComparison.OrdinalIgnoreCase) >= 0 || method.Name.IndexOf("Deserialize", StringComparison.OrdinalIgnoreCase) >= 0));
                if (type.GetAttributes().Any(value => value.AttributeClass?.ToDisplayString() == "System.Runtime.InteropServices.StructLayoutAttribute")
                    || type.GetMembers().OfType<IFieldSymbol>().Any(field => field.IsStatic && !field.IsConst && !field.IsImplicitlyDeclared)
                    || hasAutoProperty || hasEqualityContract || type.GetTypeMembers("BurstCodec").Length != 0)
                { Report(context, AbiDiagnostics.Storage, type, type.Name, "registered value has explicit layout, mutable/static/property/custom hook, or reserved BurstCodec"); valid = false; continue; }
                var fields = type.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared).ToArray();
                foreach (var field in fields)
                {
                    var attributes = field.GetAttributes().Where(value => value.AttributeClass?.ToDisplayString() == ValueFieldAttribute).ToArray();
                    if (field.DeclaredAccessibility != Accessibility.Public || attributes.Length != 1 || !AllowedType(field.Type, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), out _))
                    { Report(context, AbiDiagnostics.Storage, field, type.Name, "registered value field is not public, attributed once, or allowlisted"); valid = false; continue; }
                    var fieldAttribute = attributes[0]; var fieldId = fieldAttribute.ConstructorArguments[0].Value as string ?? string.Empty;
                    var fieldTypeId = fieldAttribute.ConstructorArguments[1].Value as string ?? string.Empty;
                    var fieldVersion = fieldAttribute.ConstructorArguments[2].Value is uint fieldVersionValue ? fieldVersionValue : 0;
                    if (!CanonicalField(fieldId)) { ReportAt(context, AbiDiagnostics.Identity, AttributeLocation(fieldAttribute, 0), field.Name); valid = false; }
                    else if (!PrimitiveIdentityMatches(field.Type, fieldTypeId, fieldVersion))
                    { ReportAt(context, AbiDiagnostics.WrongAccess, IdentityMismatchLocation(fieldAttribute, field.Type), field.Name, fieldTypeId); valid = false; }
                }
                var ordered = fields.Select(field => new StableField(field, Attribute(field, ValueFieldAttribute)!)).OrderBy(field => field.Id, Utf8StringComparer.Instance).ToArray();
                for (var index = 1; index < ordered.Length; index++)
                    if (ordered[index - 1].Id == ordered[index].Id || NumericId(ordered[index - 1].Id) == NumericId(ordered[index].Id))
                    { ReportFieldCollision(context, ordered[index - 1], ordered[index]); valid = false; }
            }
            var schemas = values.Select(type => new { Type = type, Attribute = Attribute(type, ValueAttribute)!, Id = (string)Attribute(type, ValueAttribute)!.ConstructorArguments[2].Value! })
                .OrderBy(value => value.Id, Utf8StringComparer.Instance).ToArray();
            for (var index = 1; index < schemas.Length; index++)
                if (schemas[index - 1].Id != schemas[index].Id && NumericId(schemas[index - 1].Id) == NumericId(schemas[index].Id))
                { ReportLocationCollision(context, AbiDiagnostics.NumericCollision, AttributeLocation(schemas[index].Attribute, 2), AttributeLocation(schemas[index - 1].Attribute, 2), schemas[index - 1].Id, schemas[index].Id); valid = false; }
            return valid;
        }

        private static bool PrimitiveIdentityMatches(ITypeSymbol type, string id, uint version)
        {
            string? expected = null;
            switch (type.SpecialType)
            {
                case SpecialType.System_Boolean: expected = "Bool"; break; case SpecialType.System_SByte: expected = "Int8"; break;
                case SpecialType.System_Byte: expected = "UInt8"; break; case SpecialType.System_Int16: expected = "Int16"; break;
                case SpecialType.System_UInt16: expected = "UInt16"; break; case SpecialType.System_Int32: expected = "Int32"; break;
                case SpecialType.System_UInt32: expected = "UInt32"; break; case SpecialType.System_Int64: expected = "Int64"; break;
                case SpecialType.System_UInt64: expected = "UInt64"; break; case SpecialType.System_Single: expected = "Float32"; break;
                case SpecialType.System_Double: expected = "Float64"; break;
            }
            if (expected != null) return id == expected && version == 1;
            var named = type as INamedTypeSymbol;
            if (named != null && named.IsGenericType && IsGeneratedHandle(named.ConstructedFrom.ToDisplayString()))
                return id == "GeneratedHandle" && version == 1;
            if (named != null)
            {
                var registered = Attribute(named, ValueAttribute);
                if (registered != null && registered.ConstructorArguments.Length >= 2)
                    return id == registered.ConstructorArguments[0].Value as string && version == (uint)registered.ConstructorArguments[1].Value!;
            }
            return ClosedNonScalarIdentity(type.ToDisplayString(), id, version);
        }

        private static bool ClosedNonScalarIdentity(string display, string id, uint version)
        {
            if (version != 1) return false;
            switch (display)
            {
                case "AIBT.Float2Value": return id == "Float2";
                case "AIBT.Float3Value": return id == "Float3";
                case "AIBT.QuaternionValue": return id == "Quaternion";
                case "Unity.Collections.FixedString32Bytes": return id == "FixedString32";
                case "Unity.Collections.FixedString64Bytes": return id == "FixedString64";
                case "Unity.Collections.FixedString128Bytes": return id == "FixedString128";
                case "Unity.Collections.FixedString512Bytes": return id == "FixedString512";
                case "AIBT.AgentId": return id == "AgentId";
                case "AIBT.EntityId": return id == "EntityId";
                case "AIBT.OperationId": return id == "OperationId";
                case "AIBT.AssetId": return id == "AssetId";
                default: return false;
            }
        }

        private static bool AllowedConfigurationField(ITypeSymbol type)
        {
            if (type.SpecialType == SpecialType.System_Boolean || type.SpecialType == SpecialType.System_UInt32 || type.SpecialType == SpecialType.System_UInt64) return true;
            var named = type as INamedTypeSymbol;
            return named != null && named.IsGenericType && named.Name.EndsWith("Handle", StringComparison.Ordinal);
        }

        private static bool AllowedType(ITypeSymbol type, HashSet<ITypeSymbol> visiting, out string? reason)
        {
            reason = null;
            if (type.TypeKind == TypeKind.Pointer || type.TypeKind == TypeKind.FunctionPointer)
            {
                reason = "pointer types are forbidden";
            return false;
        }

            var display = type.ToDisplayString();
            if (display == "System.IntPtr" || display == "System.UIntPtr" || display == "System.String"
                || display.StartsWith("Unity.Collections.Native", StringComparison.Ordinal)
                || display.StartsWith("UnityEngine.", StringComparison.Ordinal))
            {
                reason = display + " is not allowlisted";
                return false;
            }
            if (type.SpecialType != SpecialType.None)
            {
                switch (type.SpecialType)
                {
                    case SpecialType.System_Boolean: case SpecialType.System_SByte: case SpecialType.System_Byte:
                    case SpecialType.System_Int16: case SpecialType.System_UInt16: case SpecialType.System_Int32:
                    case SpecialType.System_UInt32: case SpecialType.System_Int64: case SpecialType.System_UInt64:
                    case SpecialType.System_Single: case SpecialType.System_Double: return true;
                    default: reason = display + " is not an ABI scalar"; return false;
                }
            }
            var named = type as INamedTypeSymbol;
            if (named == null || !named.IsUnmanagedType)
            {
                reason = display + " is managed";
                return false;
            }
            if (named.IsGenericType && IsGeneratedHandle(named.ConstructedFrom.ToDisplayString())) return true;
            if (IsClosedNonScalar(display)) return true;
            if (Attribute(named, ValueAttribute) == null)
            { reason = display + " is not a registered ABI value"; return false; }
            if (!visiting.Add(type)) return true;
            foreach (var field in named.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared))
                if (!AllowedType(field.Type, visiting, out reason)) return false;
            visiting.Remove(type);
            return true;
        }

        private static Location? IdentityMismatchLocation(AttributeData attribute, ITypeSymbol type)
        {
            var id = attribute.ConstructorArguments.Length > 1 ? attribute.ConstructorArguments[1].Value as string ?? string.Empty : string.Empty;
            uint expectedVersion = 1;
            if (type is INamedTypeSymbol named) { var registered = Attribute(named, ValueAttribute); if (registered != null && registered.ConstructorArguments.Length > 1 && registered.ConstructorArguments[1].Value is uint version) expectedVersion = version; }
            return PrimitiveIdentityMatches(type, id, expectedVersion) ? AttributeLocation(attribute, 2) : AttributeLocation(attribute, 1);
        }

        private static Location? BindingMismatchLocation(INamedTypeSymbol handle, AttributeData binding, string stableId)
        {
            var args = binding.ConstructorArguments;
            if (args.Length == 0 || !string.Equals(args[0].Value as string, stableId, StringComparison.Ordinal)) return AttributeLocation(binding, 0);
            var generic = handle.ConstructedFrom.ToDisplayString();
            if (generic == "AIBT.Burst.BlackboardReadHandle<T>" || generic == "AIBT.Burst.BlackboardWriteHandle<T>" || generic == "AIBT.Burst.BlackboardReadWriteHandle<T>")
            {
                var expectedAccess = generic == "AIBT.Burst.BlackboardReadHandle<T>" ? 0 : generic == "AIBT.Burst.BlackboardWriteHandle<T>" ? 1 : 2;
                var access = args.Length > 1 && args[1].Value != null ? Convert.ToInt32(args[1].Value, CultureInfo.InvariantCulture) : -1;
                if (access != expectedAccess) return AttributeLocation(binding, 1);
                var scope = args.Length > 2 && args[2].Value != null ? Convert.ToInt32(args[2].Value, CultureInfo.InvariantCulture) : -1;
                if (scope == 3 && access != 0) return AttributeLocation(binding, 2);
                return BindingTypeMismatchLocation(binding, handle.TypeArguments[0], 3, 4);
            }
            if (generic == "AIBT.Burst.AsyncOperationHandle<TStart, TCancel>")
            {
                var first = BindingTypeMismatchLocation(binding, handle.TypeArguments[0], 1, 2); if (first != null) return first;
                return BindingTypeMismatchLocation(binding, handle.TypeArguments[1], 3, 4) ?? AttributeLocation(binding, 3);
            }
            return BindingTypeMismatchLocation(binding, handle.TypeArguments[0], 1, 2) ?? AttributeLocation(binding, 1);
        }

        private static Location? BindingTypeMismatchLocation(AttributeData binding, ITypeSymbol type, int idArgument, int versionArgument)
        {
            if (binding.ConstructorArguments.Length <= versionArgument) return AttributeLocation(binding, idArgument);
            var id = binding.ConstructorArguments[idArgument].Value as string ?? string.Empty; var version = binding.ConstructorArguments[versionArgument].Value is uint value ? value : 0;
            if (PrimitiveIdentityMatches(type, id, version)) return null;
            uint expectedVersion = 1; if (type is INamedTypeSymbol named) { var registered = Attribute(named, ValueAttribute); if (registered != null && registered.ConstructorArguments[1].Value is uint registeredVersion) expectedVersion = registeredVersion; }
            return PrimitiveIdentityMatches(type, id, expectedVersion) ? AttributeLocation(binding, versionArgument) : AttributeLocation(binding, idArgument);
        }

