        private static ulong NumericId(string value)
        {
            if (ForceNumericIdentityCollisionForTests) return 0xfeedUL;
            var hash = 14695981039346656037UL;
            foreach (var octet in Encoding.UTF8.GetBytes(value)) { hash ^= octet; hash *= 1099511628211UL; }
            return hash;
        }
        private static bool Canonical(string value) => CanonicalSegments(value, true);
        private static bool CanonicalField(string value) => CanonicalSegments(value, false);
        private static bool CanonicalSegments(string value, bool requireDot)
        {
            if (string.IsNullOrEmpty(value) || value.Length > 255 || (requireDot && value.IndexOf('.') < 0)) return false;
            var segments = value.Split('.');
            return segments.All(segment => segment.Length != 0 && segment[0] != '-' && segment[segment.Length - 1] != '-'
                && segment.All(character => (character >= 'a' && character <= 'z') || (character >= '0' && character <= '9') || character == '-'));
        }
        private static bool ValidExampleId(string value)
        {
            if (string.IsNullOrEmpty(value) || value.Length > 128 || !AsciiAlphaNumeric(value[0])) return false;
            return value.Skip(1).All(character => AsciiAlphaNumeric(character) || character == '.' || character == '_' || character == ':' || character == '-');
        }
