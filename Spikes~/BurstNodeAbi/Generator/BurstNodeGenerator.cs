        private static FingerprintBundle Fingerprints(INamedTypeSymbol catalogSet, IEnumerable<INamedTypeSymbol> shardTypes, IReadOnlyList<Node> nodes)
        {
            var catalogAttribute = Attribute(catalogSet, CatalogSetAttribute)!;
            var catalogId = (string)catalogAttribute.ConstructorArguments[0].Value!;
            var catalogVersion = (uint)catalogAttribute.ConstructorArguments[1].Value!;
            var records = nodes.Select(NodeFingerprint.Create).OrderBy(record => record.Node.TypeId, Utf8StringComparer.Instance)
                .ThenBy(record => record.Node.Version).ToArray();
            var config = CatalogLayoutHash("AIBT-CATALOG-CONFIG-LAYOUT-V1\0", catalogId, catalogVersion, records, record => record.Configuration);
            var memory = CatalogLayoutHash("AIBT-CATALOG-MEMORY-LAYOUT-V1\0", catalogId, catalogVersion, records, record => record.Memory);
            var access = CatalogLayoutHash("AIBT-CATALOG-ACCESS-LAYOUT-V1\0", catalogId, catalogVersion, records, record => record.Access);

            var catalogBytes = new CanonicalBytes();
            catalogBytes.Raw("AIBT-CATALOG-V1\0"); catalogBytes.U32(1); catalogBytes.S(catalogId); catalogBytes.U32(catalogVersion);
            var shards = shardTypes.Select(shard => new ShardRecord(shard, Attribute(shard, ShardAttribute)!))
                .OrderBy(shard => shard.Id, Utf8StringComparer.Instance).ThenBy(shard => shard.Version).ToArray();
            catalogBytes.U32((uint)shards.Length);
            foreach (var shard in shards)
            {
                catalogBytes.S(shard.Id); catalogBytes.U32(shard.Version);
                var shardNodes = records.Where(record => SymbolEqualityComparer.Default.Equals(record.Node.Type.ContainingAssembly, shard.Type.ContainingAssembly)).ToArray();
                catalogBytes.U32((uint)shardNodes.Length);
                foreach (var record in shardNodes)
                {
                    var attr = Attribute(record.Node.Type, NodeAttribute)!; var args = attr.ConstructorArguments;
                    catalogBytes.S(record.Node.TypeId); catalogBytes.U64(NumericId(record.Node.TypeId)); catalogBytes.U32(record.Node.Version);
                    catalogBytes.U8((byte)record.Node.Kind); catalogBytes.U8((bool)args[6].Value! ? (byte)1 : (byte)0);
                    catalogBytes.U8(Convert.ToByte(args[7].Value, CultureInfo.InvariantCulture));
                    catalogBytes.U8(Convert.ToByte(args[8].Value, CultureInfo.InvariantCulture));
                    catalogBytes.U8(Convert.ToByte(args[9].Value, CultureInfo.InvariantCulture));
                    catalogBytes.U8(Convert.ToByte(args[5].Value, CultureInfo.InvariantCulture));
                    catalogBytes.U8((byte)(15 | (Attribute(record.Node.Type, ObserverAttribute) != null ? 16 : 0)));
                    catalogBytes.U8(Attribute(record.Node.Type, RandomAttribute) != null ? (byte)1 : (byte)0);
                    catalogBytes.H32(record.Configuration); catalogBytes.H32(record.Memory); catalogBytes.H32(record.Access);
                }
            }

            return new FingerprintBundle(catalogBytes.Hash(), RegistryHash(records.Select(record => record.Node).ToArray()), config, memory, access);
        }

        private static byte[] CatalogLayoutHash(string domain, string catalogId, uint catalogVersion,
            IReadOnlyList<NodeFingerprint> records, Func<NodeFingerprint, byte[]> select)
        {
            var bytes = new CanonicalBytes(); bytes.Raw(domain); bytes.U32(1); bytes.S(catalogId); bytes.U32(catalogVersion); bytes.U32((uint)records.Count);
            foreach (var record in records) { bytes.S(record.Node.TypeId); bytes.U32(record.Node.Version); bytes.H32(select(record)); }
            return bytes.Hash();
        }

        private static byte[] RegistryHash(IReadOnlyList<Node> nodes)
        {
            var builder = new StringBuilder(4096);
            builder.AppendLine("{"); JsonLine(builder, 1, "\"format\": \"aibt-node-registry\","); JsonLine(builder, 1, "\"formatVersion\": 1,");
            JsonLine(builder, 1, "\"manifests\": [");
            var ordered = nodes.OrderBy(node => node.TypeId, Utf8StringComparer.Instance).ThenBy(node => node.Version).ToArray();
            for (var index = 0; index < ordered.Length; index++)
