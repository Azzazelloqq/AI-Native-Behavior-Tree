            }
        }

        private static void EmitValueCodec(StringBuilder builder, INamedTypeSymbol value)
        {
            OpenNamespace(builder, value.ContainingNamespace);
            builder.Append("public partial struct ").Append(value.Name).AppendLine(); builder.AppendLine("{"); builder.AppendLine("    public static class BurstCodec"); builder.AppendLine("    {");
            builder.Append("        public static global::AIBT.Burst.BurstContextResult TryRead(ref global::AIBT.Burst.BurstValueReader reader, out ").Append(value.Name).AppendLine(" value)"); builder.AppendLine("        {");
            var fields = value.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && Attribute(field, ValueFieldAttribute) != null).OrderBy(StableFieldId, Utf8StringComparer.Instance).ToArray();
            for (var i = 0; i < fields.Length; i++)
            {
                var leaves = FlattenValueLeaves(fields[i].Type, string.Empty).ToArray();
                for (var leaf = 0; leaf < leaves.Length; leaf++)
                {
                    builder.Append("            ").Append(TypeKeyword(leaves[leaf].Type)).Append(" field").Append(i).Append('_').Append(leaf).AppendLine(";");
                    builder.Append("            var result").Append(i).Append('_').Append(leaf).Append(" = global::AIBT.Burst.BurstGeneratedRuntimeBridge.TryReadValue(ref reader, ").Append(i).Append("u, ").Append(leaf).Append("u, out field").Append(i).Append('_').Append(leaf).AppendLine(");");
                    builder.Append("            if (result").Append(i).Append('_').Append(leaf).AppendLine(" != global::AIBT.Burst.BurstContextResult.Success) { value = default; return result" + i + "_" + leaf + "; }");
                }
            }
            builder.Append("            value = new ").Append(value.Name).AppendLine(" {");
            for (var i = 0; i < fields.Length; i++) { var leaf = 0; builder.Append("                ").Append(fields[i].Name).Append(" = ").Append(ValueReadExpression(fields[i].Type, "field" + i + "_", ref leaf)).AppendLine(","); }
            builder.AppendLine("            };");
            builder.AppendLine("            return global::AIBT.Burst.BurstGeneratedRuntimeBridge.TryCompleteValueRead(ref reader);"); builder.AppendLine("        }");
            builder.Append("        public static global::AIBT.Burst.BurstContextResult TryWrite(ref global::AIBT.Burst.BurstValueWriter writer, in ").Append(value.Name).AppendLine(" value)"); builder.AppendLine("        {");
            for (var i = 0; i < fields.Length; i++)
            {
                var leaves = FlattenValueLeaves(fields[i].Type, "value." + fields[i].Name).ToArray();
                for (var leaf = 0; leaf < leaves.Length; leaf++) { builder.Append("            var result").Append(i).Append('_').Append(leaf).Append(" = global::AIBT.Burst.BurstGeneratedRuntimeBridge.TryWriteValue(ref writer, ").Append(i).Append("u, ").Append(leaf).Append("u, ").Append(leaves[leaf].Access).AppendLine(");"); builder.Append("            if (result").Append(i).Append('_').Append(leaf).AppendLine(" != global::AIBT.Burst.BurstContextResult.Success) return result" + i + "_" + leaf + ";"); }
            }
            builder.AppendLine("            return global::AIBT.Burst.BurstContextResult.Success;"); builder.AppendLine("        }"); builder.AppendLine("    }"); builder.AppendLine("}");
            CloseNamespace(builder, value.ContainingNamespace);
        }

        private static IEnumerable<ValueLeaf> FlattenValueLeaves(ITypeSymbol type, string access)
        {
            var named = type as INamedTypeSymbol;
            if (named == null || Attribute(named, ValueAttribute) == null) { yield return new ValueLeaf(type, access); yield break; }
            foreach (var field in named.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && Attribute(field, ValueFieldAttribute) != null).OrderBy(StableFieldId, Utf8StringComparer.Instance))
                foreach (var leaf in FlattenValueLeaves(field.Type, string.IsNullOrEmpty(access) ? field.Name : access + "." + field.Name)) yield return leaf;
        }

        private static string ValueReadExpression(ITypeSymbol type, string prefix, ref int leaf)
        {
            var named = type as INamedTypeSymbol;
            if (named == null || Attribute(named, ValueAttribute) == null) return prefix + leaf++;
            var builder = new StringBuilder("new ").Append(TypeKeyword(type)).Append(" { ");
            var fields = named.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && Attribute(field, ValueFieldAttribute) != null).OrderBy(StableFieldId, Utf8StringComparer.Instance).ToArray();
            for (var index = 0; index < fields.Length; index++) { if (index != 0) builder.Append(", "); builder.Append(fields[index].Name).Append(" = ").Append(ValueReadExpression(fields[index].Type, prefix, ref leaf)); }
            return builder.Append(" }").ToString();
        }

