        private static void SizeAndEncoding(ITypeSymbol type, out uint size, out byte alignment, out byte encoding)
        {
            switch (type.SpecialType)
            {
                case SpecialType.System_Boolean: size = 1; alignment = 1; encoding = 0; return;
                case SpecialType.System_SByte: size = 1; alignment = 1; encoding = 1; return;
                case SpecialType.System_Byte: size = 1; alignment = 1; encoding = 2; return;
                case SpecialType.System_Int16: size = 2; alignment = 2; encoding = 3; return;
                case SpecialType.System_UInt16: size = 2; alignment = 2; encoding = 4; return;
                case SpecialType.System_Int32: size = 4; alignment = 4; encoding = 5; return;
                case SpecialType.System_UInt32: size = 4; alignment = 4; encoding = 6; return;
                case SpecialType.System_Int64: size = 8; alignment = 8; encoding = 7; return;
                case SpecialType.System_UInt64: size = 8; alignment = 8; encoding = 8; return;
                case SpecialType.System_Single: size = 4; alignment = 4; encoding = 9; return;
                case SpecialType.System_Double: size = 8; alignment = 8; encoding = 10; return;
            }
            var named = (INamedTypeSymbol)type;
            if (named.IsGenericType && named.Name.EndsWith("Handle", StringComparison.Ordinal)) { size = 4; alignment = 4; encoding = 12; return; }
            switch (type.ToDisplayString())
            {
                case "AIBT.Float2Value": size = 8; alignment = 4; encoding = 11; return;
                case "AIBT.Float3Value": size = 12; alignment = 4; encoding = 11; return;
                case "AIBT.QuaternionValue": size = 16; alignment = 4; encoding = 11; return;
                case "Unity.Collections.FixedString32Bytes": size = 32; alignment = 2; encoding = 11; return;
                case "Unity.Collections.FixedString64Bytes": size = 64; alignment = 2; encoding = 11; return;
                case "Unity.Collections.FixedString128Bytes": size = 128; alignment = 2; encoding = 11; return;
                case "Unity.Collections.FixedString512Bytes": size = 512; alignment = 2; encoding = 11; return;
                case "AIBT.AgentId": case "AIBT.EntityId": size = 8; alignment = 8; encoding = 11; return;
                case "AIBT.OperationId": size = 24; alignment = 8; encoding = 11; return;
                case "AIBT.AssetId": size = 32; alignment = 8; encoding = 11; return;
            }
            var offset = 0u; var maximum = (byte)1;
            foreach (var field in named.GetMembers().OfType<IFieldSymbol>().Where(field => !field.IsStatic && !field.IsImplicitlyDeclared))
            { SizeAndEncoding(field.Type, out var fieldSize, out var fieldAlignment, out _); offset = Align(offset, fieldAlignment) + fieldSize; if (fieldAlignment > maximum) maximum = fieldAlignment; }
            size = Align(offset, maximum); alignment = maximum; encoding = 13;
        }

