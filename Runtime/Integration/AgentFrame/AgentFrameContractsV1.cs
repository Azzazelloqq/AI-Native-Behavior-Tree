using System.ComponentModel;
using AIBT.Burst;
using Unity.Collections.LowLevel.Unsafe;
using Unity.Jobs;

namespace AIBT.AgentFrame
{
    /// <summary>
    /// P10-004 generated-code infrastructure, not an application API. A catalog's generated node
    /// body entry, called by <see cref="AgentFrameJobRunnerV1"/> inside the catalog's own Burst
    /// agent-frame job for every dispatch of one agent's whole update.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public interface IAgentFrameBodyV1
    {
        BurstExecutionResult Execute(ref BurstExecutionBatch batch);
    }

    /// <summary>
    /// P10-004 generated-code infrastructure, not an application API. Implemented by the executor of
    /// catalogs generated by this package version: schedules the catalog's own Burst job that runs
    /// one agent's whole update per work item (<see cref="SchedulingPolicy.JobsAgentFrame"/>).
    /// Catalogs generated before P10-004 do not implement it, and their hosts fall back to
    /// Immediate with <see cref="AgentFrameFallbackReason.CatalogWithoutAgentFrameEntry"/>.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public interface IGeneratedAgentFrameExecutorV1
    {
        JobHandle ScheduleAgentFrame(AgentFrameJobDataV1 data, int agentCount, int innerBatchCount, JobHandle dependency);
    }

    /// <summary>
    /// P10-004 generated-code infrastructure, not an application API: the opaque per-group agent
    /// table a generated agent-frame job carries. Only the runtime creates one.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public struct AgentFrameJobDataV1
    {
        internal UnsafeList<AgentFrameAgentV1> Agents;
    }

    /// <summary>
    /// P10-004 generated-code infrastructure, not an application API: the entry a generated
    /// agent-frame job's <c>Execute(int)</c> calls for agent <paramref name="index"/>.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static class AgentFrameJobRunnerV1
    {
        public static void ExecuteAgent<TBody>(ref AgentFrameJobDataV1 data, int index)
            where TBody : struct, IAgentFrameBodyV1
        {
            var body = default(TBody);
            AgentFrameCoreV1.RunAgent(ref data.Agents.ElementAt(index), ref body);
        }

        /// <summary>Same as <see cref="ExecuteAgent{TBody}(ref AgentFrameJobDataV1,int)"/> with a caller-held body value.</summary>
        public static void ExecuteAgent<TBody>(ref AgentFrameJobDataV1 data, int index, ref TBody body)
            where TBody : struct, IAgentFrameBodyV1
            => AgentFrameCoreV1.RunAgent(ref data.Agents.ElementAt(index), ref body);
    }
}
